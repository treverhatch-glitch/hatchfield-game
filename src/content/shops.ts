export function expectedRent(shop: ConcessionType, footfallPerHour: number): number {
  if (footfallPerHour < shop.minFootfallPerHour || shop.minFootfallPerHour <= 0) {
    return 0;
  }
  const calculatedRent = shop.baseRentPerDay * (footfallPerHour / shop.minFootfallPerHour);
  const maxRent = 3 * shop.baseRentPerDay;
  return Math.min(calculatedRent, maxRent);
}
