export function assetsFor(category: BuildCategory, subtab: string, search: string): AssetDef[] {
  const q = search.trim().toLowerCase()
  return ASSETS.filter((a) => {
    if (a.category !== category) return false
    if (!q && a.subtab !== subtab) return false
    if (!q) return true
    return (
      a.name.toLowerCase().includes(q) ||
      a.blurb.toLowerCase().includes(q) ||
      a.subtab.toLowerCase().includes(q)
    )
  })
}

export function assetLock(
  game: Game,
  asset: AssetDef,
): { locked: boolean; reason: string } {
  if (asset.tool === 'stand_l' && !game.hasResearch('stand_class')) {
    return { locked: true, reason: 'Field Level 3 · Research Stand classes' }
  }
  if (asset.tool === 'deice' && !game.hasResearch('deice')) {
    return { locked: true, reason: 'Field Level 2 · Research De-ice ops' }
  }
  if (asset.tool === 'rail' && !game.railLinked) {
    return { locked: true, reason: 'Field Level 2 · Invest in City rail' }
  }
  if (asset.fieldLevel > game.fieldLevel()) {
    return { locked: true, reason: `Field Level ${asset.fieldLevel}` }
  }
  return { locked: false, reason: '' }
}

const MARKINGS_NOTE =
  'Centerline, numbers, and threshold bars are painted with the strip. There is no separate marking stamp.'

export function subtabNote(category: BuildCategory, subtab: string): string | null {
  if (category === 'pavement' && subtab === 'Markings') return MARKINGS_NOTE
  if (category === 'terminal' && subtab === 'Security/Check-in') {
    return 'Check-in desks and the screening lane are furnished inside the hall, from Services.'
  }
  return null
}
